"""Opt-in operational alerts with an allowlist that excludes prompts, users and payloads."""

import sentry_sdk

from app.config import get_settings


def scrub(event, hint):
    # Emit only our explicit code messages, without exception values, stack locals or URLs.
    message = event.get("message")
    if not isinstance(message, str) or not message.startswith("agentshelf:"):
        return None
    return {
        "event_id": event.get("event_id"),
        "timestamp": event.get("timestamp"),
        "level": event.get("level", "error"),
        "message": message,
        "environment": get_settings().app_env,
    }


def setup():
    settings = get_settings()
    if settings.sentry_dsn:
        sentry_sdk.init(
            dsn=settings.sentry_dsn.get_secret_value(),
            environment=settings.app_env,
            default_integrations=False,
            auto_enabling_integrations=False,
            send_default_pii=False,
            include_local_variables=False,
            traces_sample_rate=0,
            before_send=scrub,
        )


def report(code):
    if get_settings().sentry_dsn:
        # Codes are generated by our handlers; accept no customer/provider text.
        if not code.isupper() or not code.replace("_", "").isalpha() or len(code) > 80:
            code = "INTERNAL_ERROR"
        sentry_sdk.capture_message("agentshelf:" + code, level="error")
